/* ── i18n Engine ── */
class I18nEngine {
  constructor() {
    this.currentLang = localStorage.getItem('portfolio-lang') || 'en';
  }

  t(key) {
    return I18N[this.currentLang]?.[key] || I18N['en']?.[key] || key;
  }

  setLang(lang) {
    if (!I18N[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('portfolio-lang', lang);
    document.documentElement.lang = lang;
    this.applyTranslations();
    this.updateToggle();
    this.updateProjectModalData();
  }

  toggle() {
    this.setLang(this.currentLang === 'en' ? 'fr' : 'en');
  }

  applyTranslations() {
    /* Update <title> and <meta description> */
    document.title = this.t('meta.title');
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc) metaDesc.setAttribute('content', this.t('meta.description'));

    /* Translate all [data-i18n] elements */
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = this.t(key);
      if (el.hasAttribute('data-i18n-html')) {
        el.innerHTML = val;
      } else {
        el.textContent = val;
      }
    });
  }

  updateToggle() {
    const btn = document.getElementById('lang-toggle');
    if (btn) {
      const otherLang = this.currentLang === 'en' ? 'FR' : 'EN';
      btn.querySelector('.lang-toggle-label').textContent = otherLang;
      btn.setAttribute('aria-label', `Switch to ${otherLang === 'FR' ? 'French' : 'English'}`);
    }
  }

  updateProjectModalData() {
    /* Update the JS projectDetailsMap used by main.js */
    if (window._updateProjectDetailsI18n) {
      window._updateProjectDetailsI18n(this);
    }
  }

  init() {
    document.documentElement.lang = this.currentLang;
    this.applyTranslations();
    this.updateToggle();

    const btn = document.getElementById('lang-toggle');
    if (btn) {
      btn.addEventListener('click', (e) => {
        if (e) e.preventDefault();
        this.toggle();
      });
    }
  }
}

/* Export singleton */
window.i18n = new I18nEngine();
